#!/usr/bin/env bash
# Build a throwaway repo for the nara-pr stacked-split tasks.
# Usage: stack-repo.sh <empty-dir> <three-concerns | coherent-churn>
#
# three-concerns: one branch carries three reviewable concerns in a linear
#   dependency (model + migration -> domain rule + tests -> API route + page).
#   The commits do NOT follow those concerns, so splitting by commit is wrong
#   and the layers must be rebuilt by path ownership.
# coherent-churn: one rename refactor plus a large regenerated snapshot. Raw
#   diff is large, but there is one review concern, so it must stay single.
set -euo pipefail
dir="${1:?usage: stack-repo.sh <empty-dir> <three-concerns|coherent-churn>}"
shape="${2:?usage: stack-repo.sh <empty-dir> <three-concerns|coherent-churn>}"
mkdir -p "$dir"
# Refuse anything that is not empty: `git add -A` would commit whatever is there.
if [ -n "$(ls -A "$dir")" ]; then
  echo "refusing: $dir is not empty (pass a fresh dir, e.g. \"\$(mktemp -d)\")" >&2
  exit 2
fi
cd "$dir"
git init -q -b main
git config user.name "dev" && git config user.email "dev@example.com"

mkdir -p src tests migrations web
cat > src/models.py <<'PY'
from dataclasses import dataclass


@dataclass
class Coupon:
    code: str
    percent: int
PY
cat > src/api.py <<'PY'
ROUTES = {}


def route(path):
    def wrap(fn):
        ROUTES[path] = fn
        return fn
    return wrap
PY
cat > src/report.py <<'PY'
def total(lines):
    return sum(line.amount for line in lines)
PY
cat > src/report_api.py <<'PY'
from src.api import route
from src.report import total


@route("/report/total")
def report_total(lines):
    return {"total": total(lines)}
PY
cat > migrations/001_coupons.sql <<'SQL'
CREATE TABLE coupons (code TEXT PRIMARY KEY, percent INTEGER NOT NULL);
SQL
git add -A && git commit -q -m "chore: initial"
git update-ref refs/remotes/origin/main HEAD

case "$shape" in
three-concerns)
  git checkout -q -b feature/PROJ-90-coupon-expiry
  # Commit 1 mixes the model (layer 1) with the domain rule (layer 2).
  cat > src/models.py <<'PY'
from dataclasses import dataclass
from datetime import date
from typing import Optional


@dataclass
class Coupon:
    code: str
    percent: int
    expires_on: Optional[date] = None
PY
  cat > src/coupons.py <<'PY'
from datetime import date

from src.models import Coupon


def is_usable(coupon: Coupon, today: date) -> bool:
    if coupon.expires_on is None:
        return True
    return today <= coupon.expires_on
PY
  git add -A && git commit -qm "PROJ-90 feat: coupon expiry model and rule"
  # Commit 2 is the API route and page (layer 3).
  cat > src/api.py <<'PY'
from datetime import date

from src.coupons import is_usable

ROUTES = {}


def route(path):
    def wrap(fn):
        ROUTES[path] = fn
        return fn
    return wrap


@route("/coupons/<code>/check")
def check_coupon(coupon, today=None):
    usable = is_usable(coupon, today or date.today())
    return {"code": coupon.code, "usable": usable}
PY
  cat > web/coupon_check.html <<'HTML'
<form action="/coupons/check" method="get">
  <label for="code">쿠폰 코드</label>
  <input id="code" name="code">
  <button type="submit">사용 가능 여부 확인</button>
</form>
HTML
  git add -A && git commit -qm "PROJ-90 feat: coupon check endpoint and page"
  # Commit 3 mixes the migration (layer 1) with the domain tests (layer 2).
  cat > migrations/002_coupon_expiry.sql <<'SQL'
ALTER TABLE coupons ADD COLUMN expires_on DATE NULL;
SQL
  cat > tests/test_coupons.py <<'PY'
from datetime import date

from src.coupons import is_usable
from src.models import Coupon


def test_no_expiry_is_usable():
    assert is_usable(Coupon("A", 10), date(2026, 1, 1))


def test_expired_is_not_usable():
    assert not is_usable(Coupon("A", 10, date(2025, 12, 31)), date(2026, 1, 1))
PY
  git add -A && git commit -qm "PROJ-90 chore: migration and tests"
  ;;
coherent-churn)
  git checkout -q -b feature/PROJ-91-rename-total
  cat > src/report.py <<'PY'
def grand_total(lines):
    return sum(line.amount for line in lines)
PY
  # Pure rename: the route already exists on main; only the call site changes.
  cat > src/report_api.py <<'PY'
from src.api import route
from src.report import grand_total


@route("/report/total")
def report_total(lines):
    return {"total": grand_total(lines)}
PY
  git add -A && git commit -qm "PROJ-91 refactor: rename total to grand_total"
  mkdir -p tests/__snapshots__
  {
    echo "# generated by snapshot tool, do not edit"
    for i in $(seq 1 1500); do echo "report_total[$i] grand_total=$((i * 7))"; done
  } > tests/__snapshots__/report.snap
  git add -A && git commit -qm "PROJ-91 test: regenerate report snapshots"
  ;;
*)
  echo "unknown shape: $shape" >&2
  exit 2
  ;;
esac
echo "built $(pwd) on $(git rev-parse --abbrev-ref HEAD) at $(git rev-parse --short HEAD)"
